"""
errors.py —— 项目内的异常类型
"""

from __future__ import annotations


class TemporaryFeedError(RuntimeError):
    """
    临时性失败：限流、软封、登录态过期等，等一会儿可能自己就好了。

    这类失败**不该**触发"连续失败 3 次自动暂停该源"，否则会出这种事（实测踩到）：
    微博临时限制访问 → 自动刷新每 30 分钟试一次 → 攒够 3 次就把源永久暂停 →
    等微博恢复了，这个源却再也不会被重试，用户只能手动点"恢复"。

    所以临时失败不计入失败次数，并且保持该源可用。
    """
